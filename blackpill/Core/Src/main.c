void GUI_Init(void)
{
    lv_init();

    /* Use STM32 HAL timebase */
    lv_tick_set_cb(HAL_GetTick);

    if (BSP_LCD_Init(0,
        LCD_ORIENTATION_LANDSCAPE) != BSP_ERROR_NONE)
        Error_Handler();

    if (BSP_LCD_DisplayOn(0) != BSP_ERROR_NONE)
        Error_Handler();

    lv_display_t *disp =
        lv_display_create(LCD_WIDTH, LCD_HEIGHT);

    gui_display = disp;


    lv_display_set_color_format(
        disp, LV_COLOR_FORMAT_RGB565);

    lv_display_set_buffers(
        disp,
        lv_buffer,
        NULL,
        sizeof(lv_buffer),
        LV_DISPLAY_RENDER_MODE_PARTIAL);


    lv_display_set_flush_cb(disp, lcd_flush);


}

static uint16_t dma_test_pixels[320 * 10];

