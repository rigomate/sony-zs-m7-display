{
    for (uint32_t i = 0; i < 320 * 10; i++)
    {
        dma_test_pixels[i] = 0xF800; // Red
    }

    if (BSP_LCD_FillRGBRect(
            0,
            1,  // DMA enabled
            (uint8_t *)dma_test_pixels,
            0, 0, 320, 10
        ) != BSP_ERROR_NONE)
    {
        Error_Handler();
    }

    BSP_LCD_WaitForTransferToBeDone(0);
}





